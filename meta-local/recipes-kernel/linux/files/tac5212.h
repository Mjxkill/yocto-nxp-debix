#ifndef __TAC5212_H__
#define __TAC5212_H__

/* Page 0 registers */
#define TAC5212_PAGE_CFG		0x00
#define TAC5212_SW_RESET		0x01
#define TAC5212_DEV_MISC_CFG		0x02
#define TAC5212_AVDD_IOVDD_STS		0x03
#define TAC5212_MISC_CFG		0x04
#define TAC5212_MISC_CFG1		0x05
#define TAC5212_DAC_CFG_A0		0x06
#define TAC5212_MISC_CFG0		0x07

#define TAC5212_GPIO1_CFG0		0x0A
#define TAC5212_GPIO2_CFG0		0x0B
#define TAC5212_GPO1_CFG0		0x0C
#define TAC5212_GPI_CFG			0x0D
#define TAC5212_GPO_GPI_VAL		0x0E

#define TAC5212_INTF_CFG0		0x0F
#define TAC5212_INTF_CFG1		0x10
#define TAC5212_INTF_CFG2		0x11
#define TAC5212_INTF_CFG3		0x12
#define TAC5212_INTF_CFG4		0x13
#define TAC5212_INTF_CFG5		0x14
#define TAC5212_INTF_CFG6		0x15

#define TAC5212_ASI_CFG0		0x18
#define TAC5212_ASI_CFG1		0x19
#define TAC5212_PASI_CFG0		0x1A
#define TAC5212_PASI_TX_CFG0		0x1B
#define TAC5212_PASI_TX_CFG1		0x1C
#define TAC5212_PASI_TX_CFG2		0x1D
#define TAC5212_PASI_TX_CH1_CFG		0x1E
#define TAC5212_PASI_TX_CH2_CFG		0x1F
#define TAC5212_PASI_TX_CH3_CFG		0x20
#define TAC5212_PASI_TX_CH4_CFG		0x21
#define TAC5212_PASI_TX_CH5_CFG		0x22
#define TAC5212_PASI_TX_CH6_CFG		0x23
#define TAC5212_PASI_TX_CH7_CFG		0x24
#define TAC5212_PASI_TX_CH8_CFG		0x25
#define TAC5212_PASI_RX_CFG0		0x26
#define TAC5212_PASI_RX_CFG1		0x27
#define TAC5212_PASI_RX_CH1_CFG		0x28
#define TAC5212_PASI_RX_CH2_CFG		0x29
#define TAC5212_PASI_RX_CH3_CFG		0x2A
#define TAC5212_PASI_RX_CH4_CFG		0x2B
#define TAC5212_PASI_RX_CH5_CFG		0x2C
#define TAC5212_PASI_RX_CH6_CFG		0x2D
#define TAC5212_PASI_RX_CH7_CFG		0x2E
#define TAC5212_PASI_RX_CH8_CFG		0x2F

#define TAC5212_CLK_CFG0		0x32
#define TAC5212_CLK_CFG1		0x33
#define TAC5212_CLK_CFG2		0x34
#define TAC5212_CNT_CLK_CFG0		0x35
#define TAC5212_CNT_CLK_CFG1		0x36
#define TAC5212_CNT_CLK_CFG2		0x37
#define TAC5212_CNT_CLK_CFG3		0x38
#define TAC5212_CNT_CLK_CFG4		0x39
#define TAC5212_CNT_CLK_CFG5		0x3A
#define TAC5212_CNT_CLK_CFG6		0x3B
#define TAC5212_CLK_ERR_STS0		0x3C
#define TAC5212_CLK_ERR_STS1		0x3D
#define TAC5212_CLK_DET_STS0		0x3E
#define TAC5212_CLK_DET_STS1		0x3F
#define TAC5212_CLK_DET_STS2		0x40
#define TAC5212_CLK_DET_STS3		0x41

#define TAC5212_INT_CFG			0x42
#define TAC5212_DAC_FLT_CFG		0x43
#define TAC5212_ADC_DAC_MISC_CFG	0x4B
#define TAC5212_IADC_CFG		0x4C
#define TAC5212_VREF_MICBIAS_CFG	0x4D
#define TAC5212_PWR_TUNE_CFG0		0x4E
#define TAC5212_PWR_TUNE_CFG1		0x4F

#define TAC5212_ADC_CH1_CFG0		0x50
#define TAC5212_IADC_CH_CFG		0x51
#define TAC5212_ADC_CH1_CFG2		0x52
#define TAC5212_ADC_CH1_CFG3		0x53
#define TAC5212_ADC_CH1_CFG4		0x54
#define TAC5212_ADC_CH2_CFG0		0x55
#define TAC5212_ADC_CH2_CFG2		0x57
#define TAC5212_ADC_CH2_CFG3		0x58
#define TAC5212_ADC_CH2_CFG4		0x59

#define TAC5212_ADC_CFG1		0x62

#define TAC5212_OUT1X_CFG0		0x64
#define TAC5212_OUT1X_CFG1		0x65
#define TAC5212_OUT1X_CFG2		0x66
#define TAC5212_DAC_CH1A_CFG0		0x67
#define TAC5212_DAC_CH1A_CFG1		0x68
#define TAC5212_DAC_CH1B_CFG0		0x69
#define TAC5212_DAC_CH1B_CFG1		0x6A
#define TAC5212_OUT2X_CFG0		0x6B
#define TAC5212_OUT2X_CFG1		0x6C
#define TAC5212_OUT2X_CFG2		0x6D
#define TAC5212_DAC_CH2A_CFG0		0x6E
#define TAC5212_DAC_CH2A_CFG1		0x6F
#define TAC5212_DAC_CH2B_CFG0		0x70
#define TAC5212_DAC_CH2B_CFG1		0x71

#define TAC5212_DSP_CFG0		0x72
#define TAC5212_DSP_CFG1		0x73

#define TAC5212_CH_EN			0x76
#define TAC5212_DYN_PUPD_CFG		0x77
#define TAC5212_PWR_CFG			0x78
#define TAC5212_DEV_STS0		0x79
#define TAC5212_DEV_STS1		0x7A
#define TAC5212_I2C_CKSUM		0x7E

#define TAC5212_MAX_REG			0x7E

/* SW_RESET register */
#define TAC5212_SW_RESET_BIT		BIT(0)

/* DEV_MISC_CFG register */
#define TAC5212_SLEEP_ENZ		BIT(0)
#define TAC5212_IOVDD_IO_MODE		BIT(1)
#define TAC5212_AVDD_MODE		BIT(2)
#define TAC5212_SLEEP_EXIT_VREF_EN	BIT(3)

/* INTF_CFG1 (0x10) - reset 0x52 */
#define TAC5212_DOUT_SEL_SHIFT		4
#define TAC5212_DOUT_SEL_MASK		GENMASK(7, 4)
#define TAC5212_DOUT_DRV_SHIFT		0
#define TAC5212_DOUT_DRV_MASK		GENMASK(2, 0)

/* INTF_CFG2 (0x11) - reset 0x80 */
#define TAC5212_PASI_DIN_EN		BIT(7)

/* ASI_CFG0 (0x18) - reset 0x40 */
#define TAC5212_SASI_DIS		BIT(6)
#define TAC5212_PASI_DIS		BIT(7)

/* PASI_CFG0 (0x1A) - reset 0x30 */
#define TAC5212_PASI_FORMAT_SHIFT	6
#define TAC5212_PASI_FORMAT_MASK	GENMASK(7, 6)
#define TAC5212_PASI_WLEN_SHIFT		4
#define TAC5212_PASI_WLEN_MASK		GENMASK(5, 4)
#define TAC5212_PASI_FSYNC_POL		BIT(3)
#define TAC5212_PASI_BCLK_POL		BIT(2)

#define TAC5212_FMT_TDM			0x00
#define TAC5212_FMT_I2S			0x01
#define TAC5212_FMT_LJ			0x02

#define TAC5212_WLEN_16			0x00
#define TAC5212_WLEN_20			0x01
#define TAC5212_WLEN_24			0x02
#define TAC5212_WLEN_32			0x03

/* PASI_TX_CFG0 (0x1B) */
#define TAC5212_PASI_TX_FILL		BIT(6)
#define TAC5212_PASI_TX_KEEPER		BIT(5)
#define TAC5212_PASI_TX_EDGE		BIT(4)
#define TAC5212_PASI_TX_LSB		BIT(3)
#define TAC5212_TX_USE_INT_BCLK		BIT(2)
#define TAC5212_TX_USE_INT_FSYNC	BIT(1)
#define TAC5212_TDM_PULSE_WIDTH		BIT(0)

/* PASI_TX_CHx_CFG / PASI_RX_CHx_CFG */
#define TAC5212_CH_EN_BIT		BIT(5)
#define TAC5212_CH_SLOT_MASK		GENMASK(4, 0)

/* CLK_CFG2 (0x34) - reset 0x40 */
#define TAC5212_PLL_DIS			BIT(7)
#define TAC5212_AUTO_PLL_FR_ALLOW	BIT(6)
#define TAC5212_CLK_SRC_SEL_SHIFT	1
#define TAC5212_CLK_SRC_SEL_MASK	GENMASK(3, 1)

/* CNT_CLK_CFG2 (0x37) - reset 0x20 */
#define TAC5212_CCLK_FREQ_SEL_SHIFT	5
#define TAC5212_CCLK_FREQ_SEL_MASK	GENMASK(7, 5)
#define TAC5212_PASI_CNT_CFG		BIT(4)
#define TAC5212_FS_MODE			BIT(0)

/* CH_EN (0x76) - reset 0xCC */
#define TAC5212_IN_CH1_EN		BIT(7)
#define TAC5212_IN_CH2_EN		BIT(6)
#define TAC5212_OUT_CH1_EN		BIT(3)
#define TAC5212_OUT_CH2_EN		BIT(2)

/* PWR_CFG (0x78) */
#define TAC5212_ADC_PDZ			BIT(7)
#define TAC5212_DAC_PDZ			BIT(6)
#define TAC5212_MICBIAS_PDZ		BIT(5)

/* DEV_STS1 (0x7A) */
#define TAC5212_PLL_STS			BIT(4)

/* ADC_CH1_CFG0 (0x50) / ADC_CH2_CFG0 (0x55) */
#define TAC5212_ADC_CHx_INSRC_SHIFT	6
#define TAC5212_ADC_CHx_INSRC_MASK	GENMASK(7, 6)
#define TAC5212_ADC_CHx_IMP_SHIFT	4
#define TAC5212_ADC_CHx_IMP_MASK	GENMASK(5, 4)
#define TAC5212_ADC_CHx_CM_TOL_SHIFT	2
#define TAC5212_ADC_CHx_CM_TOL_MASK	GENMASK(3, 2)
#define TAC5212_ADC_CHx_FSCALE_VAL	BIT(1)
#define TAC5212_ADC_CHx_BW_MODE		BIT(0)

/* ADC_CH1_CFG3 (0x53) / ADC_CH2_CFG3 (0x58) - Fine Gain */
#define TAC5212_ADC_CHx_FGAIN_SHIFT	4
#define TAC5212_ADC_CHx_FGAIN_MASK	GENMASK(7, 4)

/* ADC_CH1_CFG4 (0x54) / ADC_CH2_CFG4 (0x59) - Phase Cal */
#define TAC5212_ADC_CHx_PCAL_SHIFT	2
#define TAC5212_ADC_CHx_PCAL_MASK	GENMASK(7, 2)

/* ADC_CFG1 (0x62) */
#define TAC5212_ADC_DATA_INVERT		BIT(2)

/* DSP_CFG0 (0x72) - ADC DSP */
#define TAC5212_ADC_DSP_DECI_FILT_SHIFT	6
#define TAC5212_ADC_DSP_DECI_FILT_MASK	GENMASK(7, 6)
#define TAC5212_ADC_DSP_HPF_SEL_SHIFT	4
#define TAC5212_ADC_DSP_HPF_SEL_MASK	GENMASK(5, 4)
#define TAC5212_ADC_DSP_BQ_CFG_SHIFT	2
#define TAC5212_ADC_DSP_BQ_CFG_MASK	GENMASK(3, 2)
#define TAC5212_ADC_DSP_DIS_SOFT_STEP	BIT(1)
#define TAC5212_ADC_DSP_DVOL_GANG	BIT(0)

/* DSP_CFG1 (0x73) - DAC DSP */
#define TAC5212_DAC_DSP_INTX_FILT_SHIFT	6
#define TAC5212_DAC_DSP_INTX_FILT_MASK	GENMASK(7, 6)
#define TAC5212_DAC_DSP_HPF_SEL_SHIFT	4
#define TAC5212_DAC_DSP_HPF_SEL_MASK	GENMASK(5, 4)
#define TAC5212_DAC_DSP_BQ_CFG_SHIFT	2
#define TAC5212_DAC_DSP_BQ_CFG_MASK	GENMASK(3, 2)
#define TAC5212_DAC_DSP_DIS_SOFT_STEP	BIT(1)
#define TAC5212_DAC_DSP_DVOL_GANG	BIT(0)

/* OUT1x_CFG1 (0x65) - Output 1 level/drive */
#define TAC5212_OUT1P_DRIVE_SHIFT	6
#define TAC5212_OUT1P_DRIVE_MASK	GENMASK(7, 6)
#define TAC5212_OUT1P_LVL_CTRL_SHIFT	3
#define TAC5212_OUT1P_LVL_CTRL_MASK	GENMASK(5, 3)

/* OUT1x_CFG2 (0x66) */
#define TAC5212_OUT1M_DRIVE_SHIFT	6
#define TAC5212_OUT1M_DRIVE_MASK	GENMASK(7, 6)
#define TAC5212_OUT1M_LVL_CTRL_SHIFT	3
#define TAC5212_OUT1M_LVL_CTRL_MASK	GENMASK(5, 3)

/* OUT2x_CFG1 (0x6C) - Output 2 level/drive */
#define TAC5212_OUT2P_DRIVE_SHIFT	6
#define TAC5212_OUT2P_DRIVE_MASK	GENMASK(7, 6)
#define TAC5212_OUT2P_LVL_CTRL_SHIFT	3
#define TAC5212_OUT2P_LVL_CTRL_MASK	GENMASK(5, 3)

/* OUT2x_CFG2 (0x6D) */
#define TAC5212_OUT2M_DRIVE_SHIFT	6
#define TAC5212_OUT2M_DRIVE_MASK	GENMASK(7, 6)
#define TAC5212_OUT2M_LVL_CTRL_SHIFT	3
#define TAC5212_OUT2M_LVL_CTRL_MASK	GENMASK(5, 3)

/* VREF_MICBIAS_CFG (0x4D) */
#define TAC5212_MICBIAS_LDO_GAIN	BIT(4)
#define TAC5212_MICBIAS_VAL_SHIFT	2
#define TAC5212_MICBIAS_VAL_MASK	GENMASK(3, 2)
#define TAC5212_VREF_FSCALE_SHIFT	0
#define TAC5212_VREF_FSCALE_MASK	GENMASK(1, 0)

/* DYN_PUPD_CFG (0x77) */
#define TAC5212_ADC_CH_SWAP		BIT(1)
#define TAC5212_DAC_CH_SWAP		BIT(0)

/* INTF_CFG4 (0x13) - PDM microphone configuration */
#define TAC5212_PDM_CH1_SEL		BIT(7)
#define TAC5212_PDM_CH2_SEL		BIT(6)
#define TAC5212_PDMDIN2_EDGE		BIT(5)
#define TAC5212_PDMDIN1_EDGE		BIT(4)
#define TAC5212_PDM_DIN2_SEL_SHIFT	2
#define TAC5212_PDM_DIN2_SEL_MASK	GENMASK(3, 2)
#define TAC5212_PDM_DIN1_SEL_SHIFT	0
#define TAC5212_PDM_DIN1_SEL_MASK	GENMASK(1, 0)

/* GPIO1_CFG0 (0x0A) - bits [7:4] select GPIO1 function */
#define TAC5212_GPIO1_CFG_SHIFT		4
#define TAC5212_GPIO1_CFG_MASK		GENMASK(7, 4)
#define TAC5212_GPIO_FUNC_PDMCLK	0x04

/* PDM_CLK_CFG in MISC_CFG0 (0x07) / ASI_CFG1 (0x19) */
#define TAC5212_PDM_CLK_CFG_SHIFT	6
#define TAC5212_PDM_CLK_CFG_MASK	GENMASK(7, 6)

/* Base I2C address for slot calculation */
#define TAC5212_I2C_BASE_ADDR		0x50

#endif /* __TAC5212_H__ */
